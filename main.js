function edgePath(p, c, wP, wC, nh, layout) {
  if (c.side === 3) {
    const x12 = p.x - wP / 2;
    const y12 = p.y;
    const x22 = c.x + wC / 2;
    const y22 = c.y;
    return `M ${x12} ${y12} L ${x22} ${y22}`;
  }
  if (c.side === 2) {
    const x12 = p.x;
    const y12 = p.y + nh / 2;
    const x22 = c.x;
    const y22 = c.y - nh / 2;
    const mx2 = (x12 + x22) / 2;
    return `M ${x12} ${y12} L ${mx2} ${y12} L ${mx2} ${y22} L ${x22} ${y22}`;
  }
  if (c.side === 4) {
    const x12 = p.x + wP / 2;
    const y12 = p.y;
    const x22 = c.x - wC / 2;
    const y22 = c.y;
    const mx2 = (x12 + x22) / 2;
    return `M ${x12} ${y12} L ${mx2} ${y12} L ${mx2} ${y22} L ${x22} ${y22}`;
  }
  if (p.side === 0 && c.side === 0) {
    const x12 = p.x;
    const y12 = p.y + nh / 2;
    const x22 = c.x;
    const y22 = c.y - nh / 2;
    const midY = (y12 + y22) / 2;
    return `M ${x12} ${y12} L ${x12} ${midY} L ${x22} ${midY} L ${x22} ${y22}`;
  }
  const right = c.side >= 0;
  const x1 = p.x + (right ? wP / 2 : -wP / 2);
  const y1 = p.y;
  const x2 = c.x + (right ? -wC / 2 : wC / 2);
  const y2 = c.y;
  const mx = (x1 + x2) / 2;
  return `M ${x1} ${y1} C ${mx} ${y1}, ${mx} ${y2}, ${x2} ${y2}`;
}

